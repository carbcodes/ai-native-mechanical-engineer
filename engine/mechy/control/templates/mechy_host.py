    ap.add_argument("--port", help="serial port of the arm (live mode)")
    ap.add_argument("--camera", type=int, default=None, help="camera index (default from camera.json)")
    ap.add_argument("--show", action="store_true", help="show the camera view in live mode")
    ap.add_argument("--dry-run", type=Path, metavar="REPLAY_JSON", help="replay sim/<task>/replay.json")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--noise", type=float, default=None, help="dry run: camera noise (m, default vision.noise_m)")
    ap.add_argument("--log", type=Path, default=None, help="dry run: write one JSON line per throw")
    ap.add_argument("--tune-hsv", action="store_true")
    ap.add_argument("--calibrate", action="store_true")
    args = ap.parse_args(argv)
    cfg = load_config(args.config)
    if args.dry_run:
        res = run_dry(cfg, args.dry_run, seed=args.seed, noise=args.noise, log_path=args.log)
        print(json.dumps({k: v for k, v in res.items() if k != "rows"}, indent=2))
