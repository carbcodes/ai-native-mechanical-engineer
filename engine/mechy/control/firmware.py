"""Render firmware/mechy_arm/config.h from the derived control config."""

from __future__ import annotations

import math
from pathlib import Path

from .protocol import PROTOCOL_VERSION

TEMPLATES = Path(__file__).parent / "templates"
STEP_PULSE_US = 2


def _f(x: float) -> str:
    s = f"{float(x):.7g}"
    if "e" not in s and "." not in s:
        s += ".0"
    return s + "f"


def _arr(vals, fmt=_f) -> str:
    return "{" + ", ".join(fmt(v) for v in vals) + "}"


def _mat(rows) -> str:
    return "{" + ", ".join(_arr(r) for r in rows) + "}"


def render_config_h(cfg: dict, generated_by: str) -> str:
    m = cfg["motors"]
    h = cfg["homing"]
    deg = math.degrees
    L: list[str] = []
    a = L.append
    a(f"/* config.h - generated by `{generated_by}`")
    a(f" * from design/{cfg['variant']}/params.yaml, hw/motors.yaml and hw/drivers.yaml.")
    a(" * Do not edit numbers here: change params.yaml, hw/motors.yaml, hw/drivers.yaml (or params `control:`) and regenerate.")
    a(f" * Board: {cfg['board_title']} ({cfg['mcu']}).")
    a(f" * Joint->motor mapping: {cfg['mapping_source']}.")
    a(" * Estimates: V_MAX/A_MAX come from the approximate torque curve in hw/motors.yaml and the")
    a(" * worst-case (arm stretched) load from the CAD masses; verify on the real arm (README).")
    a(" */")
    a("#ifndef MECHY_CONFIG_H")
    a("#define MECHY_CONFIG_H")
    a("")
    a(f'#define MECHY_VARIANT "{cfg["variant"]}"')
    a(f'#define MECHY_BOARD "{cfg["board"]}"')
    a(f"#define {cfg['board_define']} 1")
    a(f"#define PROTOCOL_VERSION {PROTOCOL_VERSION}")
    a(f"#define SERIAL_BAUD {cfg['serial_baud']}UL")
    a("#define N_MOTORS 4")
    a(f"#define TICK_HZ {cfg['tick_hz']}UL            /* step interrupt rate = hard per-motor step ceiling */")
    a(f"#define TICKS_PER_UPDATE {cfg['ticks_per_update']}        /* profile update at {cfg['update_hz']:.0f} Hz */")
    a(f"#define STEP_PULSE_US {STEP_PULSE_US}")
    a(f"#define MICROSTEPS {cfg['microsteps']}               /* A4988 jumpers: {cfg['microstep_jumpers']} */")
    a(f"#define MAX_STEP_RATE_HZ {cfg['max_step_rate_hz']:.0f}       /* hw/drivers.yaml max_step_rate_hz */")
    a("")
    a("/* ---- pins: motor index = joint index (0 base, 1 shoulder, 2 elbow, 3 wrist) */")
    for i, mo in enumerate(m):
        a(f"/* motor {i}: {mo['name']} -> {mo['socket']} driver; drives {mo['drives']}; "
          f"switch on {mo['switch_label']} */")
        a(f"#define STEP{i}_PIN {mo['step_pin']}")
        a(f"#define STEP{i}_PORT {mo['step_port']}")
        a(f"#define STEP{i}_BIT {mo['step_bit']}")
        a(f"#define DIR{i}_PIN {mo['dir_pin']}")
        a(f"#define EN{i}_PIN {mo['enable_pin']}")
        a(f"#define SWITCH{i}_PIN {mo['switch_pin']}")
    ens = sorted({mo["enable_pin"] for mo in m}, key=[mo["enable_pin"] for mo in m].index)
    a(f"#define N_ENABLE_PINS {len(ens)}")
    a(f"static const uint8_t ENABLE_PINS[N_ENABLE_PINS] = {{{', '.join(str(e) for e in ens)}}};   /* active low */")
    a(f"#define ESTOP_PIN {cfg['estop_pin']}            /* {cfg['estop_label']}; active low; -1 disables */")
    a(f"#define SWITCH_ACTIVE_LOW {1 if h['switch_active_low'] else 0}       /* 1: switch closes to GND, INPUT_PULLUP */")
    a("")
    a("/* ---- kinematics: theta = MAP_M * q (theta = joint-side angle each motor drives) */")
    a(f"static const float MAP_M[4][4] = {_mat(cfg['mapping'])};")
    a(f"static const float MAP_MINV[4][4] = {_mat(cfg['mapping_inv'])};")
    a("/* motor steps per rad of theta = (360/step_angle) * microsteps * pulley_teeth/20 / (2 pi) */")
    a(f"static const float STEPS_PER_RAD[4] = {_arr([mo['steps_per_rad'] for mo in m])};")
    a("/* " + ", ".join(f"{mo['name']}: {mo['steps_per_rev_motor']:.0f} steps/rev x {mo['pulley_teeth']}T/20T"
                         for mo in m) + " */")
    a(f"static const uint8_t DIR_INVERT[4] = {{{', '.join(str(int(d)) for d in cfg['dir_invert'])}}};")
    a("")
    a("/* ---- limits (joint angles, rad): params limit_deg shrunk by the soft margin */")
    a(f"static const float Q_MIN[4] = {_arr([s[0] for s in cfg['soft_limits_rad']])};   /* deg: "
      + ", ".join(f"{deg(s[0]):.1f}" for s in cfg["soft_limits_rad"]) + " */")
    a(f"static const float Q_MAX[4] = {_arr([s[1] for s in cfg['soft_limits_rad']])};   /* deg: "
      + ", ".join(f"{deg(s[1]):.1f}" for s in cfg["soft_limits_rad"]) + " */")
    a("/* per-motor caps (steps/s, steps/s^2) from the torque curve x safety, minus gravity, worst-case inertia */")
    a(f"static const float V_MAX_STEPS[4] = {_arr([mo['v_max_steps'] for mo in m])};")
    a(f"static const float A_MAX_STEPS[4] = {_arr([mo['a_max_steps'] for mo in m])};")
    a("")
    a("/* ---- homing. KIND 0: limit switch at a joint limit (one sweep toward it, then a slow edge);")
    a(" * KIND 1: index sensor (hall + magnet) anywhere in the range: bounded sweeps both ways, then the")
    a(" * centre of its window from both edges, crossed slowly in HOME_DIR. COORD 255: the sensor reads")
    a(" * the joint angle q_j; COORD k: it reads motor k's angle a_k = MAP_M[k] . q (homed joints known).")
    a(f" * HOME_POS is in that coordinate. Source: {h['source']}. */")
    a(f"static const uint8_t HOME_ORDER[4] = {{{', '.join(str(i) for i in h['order'])}}};   /* "
      + " -> ".join(h["order_names"]) + " */")
    a(f"static const uint8_t HOME_KIND[4] = {{{', '.join({'limit': '0', 'index': '1', 'none': '2'}[k] for k in h['kind'])}}};   /* "
      + ", ".join(f"{n} {k}" for n, k in zip(cfg["joint_names"], h["kind"])) + " */")
    a(f"static const uint8_t HOME_COORD[4] = {{{', '.join('255' if c is None else str(c) for c in h['coord_motor'])}}};"
      "   /* " + ", ".join(h["coord"]) + " */")
    a(f"static const int8_t HOME_DIR[4] = {{{', '.join(str(d) for d in h['dir'])}}};")
    a(f"static const float HOME_POS[4] = {_arr(h['pos_rad'])};   /* deg: "
      + ", ".join(f"{deg(p):.1f}" for p in h["pos_rad"]) + " */")
    a(f"static const float HOME_TRAVEL[4] = {_arr(h['travel_rad'])};")
    a(f"#define HOME_FAST {_f(h['fast_rad_s'])}        /* rad/s ({deg(h['fast_rad_s']):.0f} deg/s) */")
    a(f"#define HOME_SLOW {_f(h['slow_rad_s'])}        /* rad/s ({deg(h['slow_rad_s']):.0f} deg/s) */")
    a(f"#define HOME_BACKOFF {_f(h['backoff_rad'])}     /* rad ({deg(h['backoff_rad']):.0f} deg) */")
    a(f"#define HOME_WINDOW {_f(h['window_rad'])}      /* rad ({deg(h['window_rad']):.0f} deg): widest sensor window */")
    a(f"#define HOME_MARGIN {_f(h['margin_rad'])}      /* rad ({deg(h['margin_rad']):.0f} deg): index sweep overrun */")
    a(f"static const float READY_POSE[4] = {_arr(cfg['ready_pose_rad'])};   /* deg: "
      + ", ".join(f"{deg(p):.1f}" for p in cfg["ready_pose_rad"]) + " */")
    a("")
    a("#endif")
    return "\n".join(L) + "\n"


def firmware_source() -> str:
    return (TEMPLATES / "mechy_arm.ino").read_text()
